// Package fcm is an Arandu module that pushes to phones, Android and iOS,
// through Firebase Cloud Messaging.
//
// It keeps the devices of the tenant's users, registered by the mobile
// application with the token Firebase gave the installation, and it is a
// channel of the hesape Notifier: a notification that names ChannelFCM in Via and
// builds a Push reaches every phone of its recipient.
//
// The files are laid out by role rather than by layer, so the whole package
// reads top to bottom:
//
//	module.go       -> registration, routes, handlers, jobs, schedule and migrations
//	config.go       -> what the application passes in
//	credentials.go  -> the service account, read from the environment, never printed
//	model.go        -> the Device entity, and what it may answer with
//	DeviceQuery.go  -> the query on that table, generated by aru model:build
//	policy.go       -> who may do what
//	service.go      -> DeviceService: register, unregister, list, and the clean
//	message.go      -> Push, the message of the channel
//	channel.go      -> the hesape notifications.Channel
//	push.go         -> delivering a push to a device, directly or as a queue job
//	client.go       -> the only file that speaks HTTP: Firebase and its OAuth2 exchange
//	fake.go         -> a Sender for the application's tests
//	seal.go         -> sealing the tokens at rest
//	audit.go        -> the events stored in the application's outbox
//
// An application registers it explicitly. There is no service provider, no
// container and no discovery: the wiring is the lines somebody wrote in
// bootstrap/app.go, and reading them is how they learn what the application is
// made of.
package fcm

import (
	"context"
	"errors"
	"fmt"
	stdhttp "net/http"
	"time"

	"github.com/arandu-io/framework/data"
	"github.com/arandu-io/framework/foundation"
	fhttp "github.com/arandu-io/framework/http"
	"github.com/arandu-io/framework/http/middleware"
	"github.com/arandu-io/framework/security"
	"github.com/arandu-io/hesape/database/migrations"
	"github.com/arandu-io/hesape/database/schema"
	"github.com/arandu-io/hesape/queue"
)

// Module is what the application registers.
//
// It implements foundation.Module, which is Name and Routes and nothing else --
// that pair is the whole public contract between a package and the framework.
// It also implements foundation.Migratable, because it owns a table, and
// foundation.Schedulable, because it declares the clean of stale devices.
type Module struct {
	cfg      Config
	devices  *DeviceService
	pusher   *pusher
	channel  *Channel
	sessions *security.SessionStore
}

// Compile-time proof that the module honors the contracts it claims.
var (
	_ foundation.Module      = (*Module)(nil)
	_ foundation.Migratable  = (*Module)(nil)
	_ foundation.Schedulable = (*Module)(nil)
)

// New returns the module, or the reason it cannot be built.
//
// The collaborators are parameters and not fields somebody fills in afterwards:
// a module that could be registered half-wired is a module whose first request
// is the thing that reports the missing half. sessions can be nil only when the
// routes are off.
//
// It returns an error rather than panicking or carrying on, because everything
// it refuses is a wiring mistake, and a wiring mistake found at boot costs one
// restart.
func New(cfg Config, db *data.DB, sessions *security.SessionStore) (*Module, error) {
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	if db == nil {
		return nil, errors.New("fcm: New needs a database handle: this package owns a table, and there is no in-memory mode that would let it start without one")
	}
	if cfg.Routes && sessions == nil {
		return nil, errors.New("fcm: New needs a session store when Config.Routes is on: every route is mounted behind RequireAuth, which reads it to admit a request and to put who is asking on it")
	}
	cfg = cfg.withDefaults()

	devices, err := NewDeviceService(db, cfg)
	if err != nil {
		return nil, err
	}
	sender := cfg.Sender
	if sender == nil {
		sender, err = NewClient(ClientConfig{
			Credentials: cfg.Credentials,
			APIBase:     cfg.APIBase,
			HTTPClient:  cfg.HTTPClient,
			Clock:       cfg.Clock,
		})
		if err != nil {
			return nil, err
		}
	}
	p := &pusher{
		devices:   devices,
		sender:    sender,
		queue:     cfg.Queue,
		queueName: cfg.QueueName,
		tries:     cfg.Tries,
		now:       cfg.Clock,
		log:       cfg.Logger,
	}
	return &Module{
		cfg:      cfg,
		devices:  devices,
		pusher:   p,
		channel:  &Channel{devices: devices, pusher: p, notifiableType: cfg.NotifiableType},
		sessions: sessions,
	}, nil
}

// Name is the module identifier: a lowercase slug, stable, no spaces.
//
// It is what `aru route:list` groups by and what the route names are prefixed
// with, so changing it changes addresses that other code has already written
// down.
func (m *Module) Name() string { return "fcm" }

// Channel is the hesape notifications channel for push. Hand it to
// notifications.New beside the application's other channels.
func (m *Module) Channel() *Channel { return m.channel }

// Devices is the service that registers, removes and lists devices, for an
// application that wraps it in routes of its own.
func (m *Module) Devices() *DeviceService { return m.devices }

// Routes registers the optional JSON routes under the configured prefix. With
// Config.Routes off it registers nothing.
//
// They are named, so a URL is built from a name rather than written out a
// second time somewhere else. Every route needs somebody signed in, so the guard
// is mounted once, on the router they are registered on, rather than route by
// route.
func (m *Module) Routes(r *fhttp.Router) {
	if !m.cfg.Routes {
		return
	}
	r = r.Group("", middleware.RequireAuth(m.sessions))

	p := m.cfg.Prefix
	r.Action(stdhttp.MethodGet, p, m.index).Name("fcm.devices.index")
	r.Action(stdhttp.MethodPost, p, m.store).Name("fcm.devices.store")
	r.Action(stdhttp.MethodPost, p+"/unregister", m.unregister).Name("fcm.devices.unregister")
	r.Action(stdhttp.MethodDelete, p+"/{id}", m.destroy).Name("fcm.devices.destroy")
}

// Handlers are thin on purpose: read the input, ask the service, answer. No
// rule, database handle or Model construction lives here. Who is asking comes
// from ctx.User, which reads the subject RequireAuth put on the request. An
// error from the service is returned as it is, and the router answers it:
// validation.Errors with 422, ErrNotFound with 404, a policy refusal with 403.

// index answers the devices of the subject.
func (m *Module) index(ctx *fhttp.Context) error {
	who, _ := ctx.User()
	devices, err := m.devices.ListForUser(ctx.Ctx(), who, "")
	if err != nil {
		return err
	}
	return ctx.JSON(stdhttp.StatusOK, NewDevicesResource(devices))
}

// store registers the phone of the subject. The body names the token, the
// platform, the app and the locale; the tenant and the owner are never read from
// it.
func (m *Module) store(ctx *fhttp.Context) error {
	in := RegisterRequest{
		Token:    ctx.Input("token"),
		Platform: ctx.Input("platform"),
		App:      ctx.Input("app"),
		Locale:   ctx.Input("locale"),
	}
	who, _ := ctx.User()
	device, err := m.devices.Register(ctx.Ctx(), who, in)
	if err != nil {
		return err
	}
	return ctx.JSON(stdhttp.StatusOK, NewDeviceResource(device))
}

// unregister removes the phone that holds the token in the body.
func (m *Module) unregister(ctx *fhttp.Context) error {
	who, _ := ctx.User()
	if err := m.devices.Unregister(ctx.Ctx(), who, ctx.Input("token")); err != nil {
		return err
	}
	return ctx.Status(stdhttp.StatusNoContent)
}

// destroy removes one device by its id.
func (m *Module) destroy(ctx *fhttp.Context) error {
	who, _ := ctx.User()
	if err := m.devices.UnregisterID(ctx.Ctx(), who, ctx.Param("id")); err != nil {
		return err
	}
	return ctx.Status(stdhttp.StatusNoContent)
}

// RegisterJobHandlers registers the job that delivers a push with the host
// application's queue worker. It is the application's to call, beside the
// handlers of its other modules, and it is needed only when Config.Queue is set.
func (m *Module) RegisterJobHandlers(worker *queue.Worker) error {
	if worker == nil {
		return errors.New("fcm: RegisterJobHandlers needs a worker")
	}
	if _, taken := worker.Handler(JobPush); taken {
		return fmt.Errorf("fcm: the worker already has a handler for %s", JobPush)
	}
	worker.Handle(JobPush, queue.HandlerFor(m.pusher.handle))
	return nil
}

// Schedule declares the daily clean of the devices that have not registered
// themselves for StaleAfterDays. It is one pass over every tenant that has
// devices, each with a Grant for that tenant alone. CleanSpec "-" declares none.
func (m *Module) Schedule() []foundation.Task {
	if m.cfg.CleanSpec == "-" {
		return nil
	}
	return []foundation.Task{{
		ID:        "fcm.devices.clean",
		Spec:      m.cfg.CleanSpec,
		Scope:     foundation.Global,
		Timeout:   10 * time.Minute,
		Singleton: true,
		Action:    DeviceClean,
		Run: func(ctx context.Context, _ security.Grant) error {
			return m.Clean(ctx)
		},
	}}
}

// Clean removes, in every tenant, the devices that have not registered
// themselves for StaleAfterDays. Schedule runs it daily; an application with a
// scheduler of its own calls it from there.
func (m *Module) Clean(ctx context.Context) error {
	cutoff := m.cfg.Clock().UTC().AddDate(0, 0, -m.cfg.StaleAfterDays)
	return eachTenant(ctx, m.devices.db, devicesTable, func(tenant string) error {
		//arandu:system-grant the tenant has devices in this module's table; the clean removes only its devices not registered since the cutoff.
		_, err := m.devices.clean(ctx, security.SystemGrant(DeviceClean, tenant), cutoff)
		return err
	})
}

// eachTenant runs fn once for every valid tenant with a row in one of this
// module's tables. It reads the tenant column and nothing else; every row fn
// reaches, it reaches with a Grant of that tenant.
func eachTenant(ctx context.Context, db *data.DB, table string, fn func(tenant string) error) error {
	rows, err := db.QueryContext(ctx, "SELECT DISTINCT tenant_id FROM "+table)
	if err != nil {
		return err
	}
	var tenants []string
	for rows.Next() {
		var tenant string
		if err := rows.Scan(&tenant); err != nil {
			_ = rows.Close()
			return err
		}
		if security.ValidTenant(tenant) {
			tenants = append(tenants, tenant)
		}
	}
	if err := errors.Join(rows.Err(), rows.Close()); err != nil {
		return err
	}
	for _, tenant := range tenants {
		if err := fn(tenant); err != nil {
			return err
		}
	}
	return nil
}

// Migrations declares the schema this module owns: the devices. The jobs table
// is the queue's, and the outbox the events are stored in is hesape's events,
// both migrated by the application.
//
// They are returned in the order their names sort in, which is the order they
// apply in: the name carries the order, and nothing else decides it.
func (m *Module) Migrations() []foundation.Migration {
	return []foundation.Migration{createDevices{}}
}

// The migration is reversible, and the assertion is here rather than discovered
// at rollback: the migrator tests for Down with a type assertion, so a Down with
// the wrong signature would leave a rollback that silently does nothing.
var _ migrations.ReversibleMigration = createDevices{}

// createDevices is the table this module owns, and the indexes its reads go by.
type createDevices struct{ migrations.BaseMigration }

// GetName is the migration's identity, and it carries the order. It is fixed
// once the package is published: changing what an applied name means leaves the
// change missing everywhere it already ran, and nothing says so.
func (createDevices) GetName() string { return "20261031_0001_create_fcm_devices" }

// Up creates the table. The timestamps have no database default: the value comes
// from Go.
func (createDevices) Up(ctx context.Context, conn migrations.Connection) error {
	return conn.Schema().Create(ctx, devicesTable, func(table *schema.Blueprint) {
		table.String("id", 64).Primary()
		table.String("tenant_id", 64)
		table.String("user_id", 64)
		table.Text("token")
		table.String("token_hash", 64)
		table.String("platform", 16)
		table.String("app", 200).Default("")
		table.String("locale", 35).Default("")
		table.Timestamp("last_seen_at")
		table.Timestamp("created_at")
		table.Timestamp("updated_at")

		// One row per token in a tenant: registering it again finds this row.
		table.Unique([]string{"tenant_id", "token_hash"}, "fcm_devices_token_uq")
		// A user's phones, which is what a push and a listing read.
		table.Index([]string{"tenant_id", "user_id", "created_at"}, "fcm_devices_user_idx")
		// The clean reads what was not seen since a date.
		table.Index([]string{"tenant_id", "last_seen_at"}, "fcm_devices_seen_idx")
	})
}

// Down drops the table, which takes its indexes with it.
func (createDevices) Down(ctx context.Context, conn migrations.Connection) error {
	return conn.Schema().DropIfExists(ctx, devicesTable)
}
